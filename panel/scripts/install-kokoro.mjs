#!/usr/bin/env node
/*
 * Installer for a local Kokoro-FastAPI TTS server.
 *
 * Clones remsky/Kokoro-FastAPI at KOKORO_FASTAPI_REF into
 * `PAVILIO_KOKORO_DIR ?? ~/.local/share/pavilio/kokoro-fastapi`, writes a
 * `kokoroctl` (start|stop|restart|status|log) beside the clone, points the panel
 * secrets file at both (KOKORO_TTS_BASE_URL, and kokoroctl appended to the
 * `:`-separated PANEL_TTS_SERVER_CTL list), then starts the
 * server once to prove it answers and stops it again (a server already running is
 * only probed, or restarted onto a new ref, never stopped). `scripts/panel` drives
 * kokoroctl start/stop from then on.
 *
 * Re-running converges: same ref, same kokoroctl and same lines change nothing.
 * `--uninstall` stops the server, removes its own files (and the dir once empty), removes
 * KOKORO_TTS_BASE_URL only when it still names this install, and drops only the kokoroctl
 * entry from PANEL_TTS_SERVER_CTL (the line goes once nothing remains); foreign entries stay.
 * It edits only the secrets file: a PANEL_TTS_SERVER_CTL in the environment that still lists
 * kokoroctl gets a warning, since the user has to update it separately.
 *
 * Every side effect outside its own files (git, kokoroctl, fetch, clock) is
 * injected into `main`, so tests run without network or a real server.
 *
 * Run as `pnpm install:kokoro` (or `bash scripts/install:kokoro`).
 */
import { spawnSync } from "node:child_process";
import {
  chmodSync,
  copyFileSync,
  existsSync,
  mkdirSync,
  readFileSync,
  realpathSync,
  rmdirSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { homedir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const KOKORO_FASTAPI_REF = "v0.9.2";
export const KOKORO_FASTAPI_REPO = "https://github.com/remsky/Kokoro-FastAPI.git";
export const KOKORO_HOST = "127.0.0.1";
export const KOKORO_PORT = 8880;
export const KOKORO_ADDRESS = `http://${KOKORO_HOST}:${KOKORO_PORT}`;
// The first start downloads the model, which is what this budget is for.
export const PROBE_TIMEOUT_MS = 300_000;
const PROBE_INTERVAL_MS = 2_000;
const PROBE_REQUEST_MS = 5_000;

const URL_VAR = "KOKORO_TTS_BASE_URL";
const CTL_VAR = "PANEL_TTS_SERVER_CTL";
const PREREQUISITES = ["git", "uv", "espeak-ng"];
const CLONE_NAME = "Kokoro-FastAPI";
// Everything the installer or kokoroctl puts in the install dir; uninstall removes only these.
const OWN_ENTRIES = [CLONE_NAME, "kokoroctl", "kokoro.pid", "kokoro.log"];
const LINE = /^([A-Za-z_][A-Za-z0-9_]*)=(.*)$/;

/** The upstream start script for this platform; both honour HOST/PORT. */
function startScript(platform) {
  return platform === "darwin" ? "start-gpu_mac.sh" : "start-cpu.sh";
}

/** The control script, generated per platform. Paths are relative to its own location. */
export function kokoroctlScript({ platform }) {
  return `#!/bin/bash
# Generated by panel/scripts/install-kokoro.mjs; re-run \`pnpm install:kokoro\` instead of editing.
# Usage: kokoroctl start|stop|restart|status|log
set -u

DIR="$(cd "$(dirname "\${BASH_SOURCE[0]}")" && pwd)"
REPO="$DIR/${CLONE_NAME}"
PIDFILE="$DIR/kokoro.pid"
LOG="$DIR/kokoro.log"
START_SCRIPT="${startScript(platform)}"

export HOST=${KOKORO_HOST}
export PORT=${KOKORO_PORT}
# The panel may launch this with a minimal PATH; uv's installer and brew live here.
export PATH="$PATH:$HOME/.local/bin:$HOME/.cargo/bin:/opt/homebrew/bin:/usr/local/bin"

# Whitespace squeezed: ps pads lstart, and read would trim it back off.
started_at() {
  ps -o lstart= -p "$1" 2>/dev/null | tr -s ' ' | sed 's/^ //; s/ $//'
}

# The pidfile holds the pid and its start time. A pid alone can be reused by an
# unrelated process, which stop would then kill; so it must still lead its own
# group and have started when recorded, else the pidfile is stale and goes.
running() {
  [ -f "$PIDFILE" ] || return 1
  local pid recorded
  { read -r pid; read -r recorded; } <"$PIDFILE"
  if [[ "$pid" =~ ^[0-9]+$ ]] && [ -n "$recorded" ] && kill -0 "$pid" 2>/dev/null \\
    && [ "$(ps -o pgid= -p "$pid" 2>/dev/null | tr -d ' ')" = "$pid" ] \\
    && [ "$(started_at "$pid")" = "$recorded" ]; then
    PID="$pid"
    return 0
  fi
  rm -f "$PIDFILE"
  return 1
}

start() {
  if running; then
    echo "kokoro: already running (pid $PID)"
    return 0
  fi
  cd "$REPO" || { echo "kokoro: $REPO is missing" >&2; return 1; }
  # The upstream script runs \`uv pip install -e .\`, which needs a venv to install into.
  if [ ! -d .venv ]; then
    uv venv >>"$LOG" 2>&1 || { echo "kokoro: uv venv failed (see $LOG)" >&2; return 1; }
  fi
  # Own process group, so stop can take down the whole uv -> uvicorn tree.
  set -m
  nohup bash "./$START_SCRIPT" >>"$LOG" 2>&1 </dev/null &
  local pid=$!
  set +m
  printf '%s\\n%s\\n' "$pid" "$(started_at "$pid")" >"$PIDFILE"
  echo "kokoro: started (pid $pid, http://$HOST:$PORT, log $LOG)"
}

stop() {
  if ! running; then
    rm -f "$PIDFILE"
    echo "kokoro: not running"
    return 0
  fi
  local pid="$PID" i=0
  kill -TERM -- "-$pid" 2>/dev/null || kill -TERM "$pid" 2>/dev/null
  while kill -0 "$pid" 2>/dev/null && [ "$i" -lt 40 ]; do
    sleep 0.25
    i=$((i + 1))
  done
  kill -KILL -- "-$pid" 2>/dev/null || kill -KILL "$pid" 2>/dev/null
  rm -f "$PIDFILE"
  echo "kokoro: stopped"
}

case "\${1:-}" in
  start) start ;;
  stop) stop ;;
  restart) stop && start ;;
  status)
    if running; then
      echo "kokoro: running (pid $PID, http://$HOST:$PORT)"
    else
      echo "kokoro: stopped"
      exit 3
    fi
    ;;
  log)
    echo "$LOG"
    [ -f "$LOG" ] && tail -n "\${2:-100}" "$LOG"
    ;;
  *)
    echo "usage: $0 start|stop|restart|status|log" >&2
    exit 2
    ;;
esac
`;
}

/* ─────────────────────────── default side effects ─────────────────────────── */

function defaultWhich(cmd) {
  return spawnSync("sh", ["-c", 'command -v "$1" >/dev/null', "sh", cmd]).status === 0;
}

function defaultGit(args) {
  const res = spawnSync("git", args, { encoding: "utf8", stdio: ["ignore", "pipe", "inherit"] });
  return { status: res.status ?? 1, stdout: res.stdout ?? "" };
}

function defaultCtl(ctlPath, verb) {
  const res = spawnSync(ctlPath, [verb], { stdio: ["ignore", "inherit", "inherit"] });
  return { status: res.status ?? 1 };
}

/* ───────────────────────────────── helpers ───────────────────────────────── */

function installHint(platform, missing) {
  if (platform === "darwin") return [`brew install ${missing.join(" ")}`];
  if (platform === "linux") {
    const hints = [];
    const apt = missing.filter((cmd) => cmd !== "uv");
    if (apt.length) hints.push(`sudo apt install ${apt.join(" ")}`);
    if (missing.includes("uv")) hints.push("curl -LsSf https://astral.sh/uv/install.sh | sh");
    return hints;
  }
  return [`install: ${missing.join(", ")}`];
}

/** Optional surrounding quotes and a CR are stripped, as scripts/panel does. */
function unquote(value) {
  const v = value.replace(/\r$/, "");
  if (v.length >= 2 && (v[0] === '"' || v[0] === "'") && v.at(-1) === v[0]) return v.slice(1, -1);
  return v;
}

function readSecretLines(file) {
  if (!existsSync(file)) return [];
  const lines = readFileSync(file, "utf8").split(/\r?\n/);
  if (lines.at(-1) === "") lines.pop();
  return lines;
}

/** The last `name=` line's value, as scripts/panel reads PANEL_TTS_SERVER_CTL. */
function fileValue(lines, name) {
  let value;
  for (const line of lines) {
    const match = LINE.exec(line);
    if (match?.[1] === name) value = unquote(match[2]);
  }
  return value || undefined;
}

/**
 * Write `lines` over the secrets file in place (keeps its mode and inode), backing
 * up the old content first. Nothing at all happens when the content is unchanged.
 */
function writeSecretLines(file, lines, now) {
  const text = lines.length ? `${lines.join("\n")}\n` : "";
  const existed = existsSync(file);
  if (existed && readFileSync(file, "utf8") === text) return false;
  if (existed) {
    const stamp = new Date(now()).toISOString().replace(/[:.]/g, "-");
    const backup = `${file}.bak-${stamp}`;
    copyFileSync(file, backup);
    chmodSync(backup, 0o600);
  } else {
    mkdirSync(resolve(file, ".."), { recursive: true, mode: 0o700 });
  }
  writeFileSync(file, text, { mode: 0o600 });
  return true;
}

/** Set each entry on its first line (dropping repeats), appending the ones that are absent. */
function withValues(lines, entries) {
  const placed = new Set();
  const out = [];
  for (const line of lines) {
    const name = LINE.exec(line)?.[1];
    if (name === undefined || !(name in entries)) {
      out.push(line);
      continue;
    }
    if (!placed.has(name)) out.push(`${name}=${entries[name]}`);
    placed.add(name);
  }
  for (const [name, value] of Object.entries(entries)) {
    if (!placed.has(name)) out.push(`${name}=${value}`);
  }
  return out;
}

/** A `:`-separated ctl list's entries, empty ones dropped, as scripts/panel reads it. */
function ctlEntries(value) {
  return (value ?? "").split(":").filter(Boolean);
}

/* ──────────────────────────────── the steps ──────────────────────────────── */

/** `updated` is true when the checkout changed, so a running server needs a restart. */
function cloneOrUpdate(git, installDir, cloneDir, log) {
  if (!existsSync(cloneDir)) {
    mkdirSync(installDir, { recursive: true });
    log(`kokoro: cloning ${KOKORO_FASTAPI_REPO} at ${KOKORO_FASTAPI_REF}`);
    const res = git(["clone", "-q", "--depth", "1", "--branch", KOKORO_FASTAPI_REF, KOKORO_FASTAPI_REPO, cloneDir]);
    return res.status === 0 ? { updated: true } : { error: `git clone failed (exit ${res.status})` };
  }
  const current = git(["-C", cloneDir, "describe", "--tags", "--exact-match", "HEAD"]);
  if (current.status === 0 && current.stdout.trim() === KOKORO_FASTAPI_REF) {
    log(`kokoro: ${cloneDir} already at ${KOKORO_FASTAPI_REF}`);
    return { updated: false };
  }
  log(`kokoro: updating ${cloneDir} to ${KOKORO_FASTAPI_REF}`);
  const fetched = git(["-C", cloneDir, "fetch", "-q", "--depth", "1", "origin", "tag", KOKORO_FASTAPI_REF]);
  if (fetched.status !== 0) return { error: `git fetch failed (exit ${fetched.status})` };
  const checkedOut = git(["-C", cloneDir, "checkout", "-q", KOKORO_FASTAPI_REF]);
  return checkedOut.status === 0 ? { updated: true } : { error: `git checkout failed (exit ${checkedOut.status})` };
}

function writeKokoroctl(ctlPath, platform) {
  const text = kokoroctlScript({ platform });
  if (!existsSync(ctlPath) || readFileSync(ctlPath, "utf8") !== text) {
    writeFileSync(ctlPath, text, { mode: 0o755 });
  }
  chmodSync(ctlPath, 0o755);
}

async function probe({ fetch, now, sleep }) {
  const url = `${KOKORO_ADDRESS}/v1/audio/voices`;
  const deadline = now() + PROBE_TIMEOUT_MS;
  for (;;) {
    try {
      const res = await fetch(url, { signal: AbortSignal.timeout(PROBE_REQUEST_MS) });
      if (res.ok) return true;
    } catch {
      // Not up yet: the server is still installing or downloading the model.
    }
    if (now() >= deadline) return false;
    await sleep(PROBE_INTERVAL_MS);
  }
}

const PANEL_DIR = resolve(dirname(fileURLToPath(import.meta.url)), "..");

/**
 * Returns the exit code instead of exiting, so a test can drive it with fakes.
 */
export async function main(
  argv,
  {
    env = process.env,
    platform = process.platform,
    which = defaultWhich,
    git = defaultGit,
    ctl = defaultCtl,
    fetch = globalThis.fetch,
    now = Date.now,
    sleep = (ms) => new Promise((r) => setTimeout(r, ms)),
    log = console.log,
    error = console.error,
    panelDir = PANEL_DIR,
  } = {},
) {
  const home = env.HOME || homedir();
  const installDir = resolve(env.PAVILIO_KOKORO_DIR || join(home, ".local", "share", "pavilio", "kokoro-fastapi"));
  const cloneDir = join(installDir, CLONE_NAME);
  const ctlPath = join(installDir, "kokoroctl");
  const logPath = join(installDir, "kokoro.log");
  // The server runs with cwd panel/ and uses the value as-is, so a relative one is panel-relative.
  const secretsFile = join(resolve(panelDir, env.PANEL_AUTH_STATE_DIR || join(home, ".panel")), "secrets.env");

  if (argv.includes("--uninstall")) {
    if (existsSync(ctlPath)) ctl(ctlPath, "stop");
    // Only what the installer and kokoroctl create; the dir may hold other files.
    for (const name of OWN_ENTRIES) rmSync(join(installDir, name), { recursive: true, force: true });
    try {
      rmdirSync(installDir);
    } catch (e) {
      if (e.code === "ENOTEMPTY" || e.code === "EEXIST") log(`kokoro: kept ${installDir}; it holds files this installer did not create`);
      else if (e.code !== "ENOENT") throw e;
    }
    const lines = readSecretLines(secretsFile);
    const kept = lines.flatMap((line) => {
      const match = LINE.exec(line);
      if (!match) return [line];
      const value = unquote(match[2]);
      if (match[1] === URL_VAR && value === KOKORO_ADDRESS) return [];
      if (match[1] !== CTL_VAR) return [line];
      const entries = ctlEntries(value);
      if (!entries.includes(ctlPath)) return [line];
      const rest = entries.filter((entry) => entry !== ctlPath);
      return rest.length ? [`${CTL_VAR}=${rest.join(":")}`] : [];
    });
    if (existsSync(secretsFile)) writeSecretLines(secretsFile, kept, now);
    log(`kokoro: removed ${installDir}`);
    // scripts/panel prefers a non-empty environment value over the secrets file; that one is the user's to edit.
    if (ctlEntries(env[CTL_VAR]).includes(ctlPath)) {
      error(`kokoro: warning: ${CTL_VAR} in the environment still lists ${ctlPath}; update it separately`);
    }
    return 0;
  }

  const missing = PREREQUISITES.filter((cmd) => !which(cmd));
  if (missing.length) {
    error(`kokoro: missing ${missing.join(", ")}; install with:`);
    for (const hint of installHint(platform, missing)) error(`  ${hint}`);
    return 1;
  }
  // The list is ':'-separated, so a ':' in the path would split into bogus entries.
  if (ctlPath.includes(":")) {
    error(`kokoro: ${ctlPath} contains ':'; ${CTL_VAR} cannot hold a path with ':' — set PAVILIO_KOKORO_DIR to a path without one`);
    return 1;
  }

  // kokoroctl joins the list; other servers' ctls stay, in their order. When the
  // effective (last) PANEL_TTS_SERVER_CTL line already lists it, the file is left byte-for-byte.
  const lines = readSecretLines(secretsFile);
  const fileCtls = ctlEntries(fileValue(lines, CTL_VAR));
  const ctlLine = fileCtls.includes(ctlPath) ? {} : { [CTL_VAR]: [...fileCtls, ctlPath].join(":") };

  const checkout = cloneOrUpdate(git, installDir, cloneDir, log);
  if (checkout.error) {
    error(`kokoro: ${checkout.error}`);
    return 1;
  }
  writeKokoroctl(ctlPath, platform);

  const changed = writeSecretLines(
    secretsFile,
    withValues(lines, { [URL_VAR]: KOKORO_ADDRESS, ...ctlLine }),
    now,
  );
  log(`kokoro: ${secretsFile} ${changed ? "updated" : "already up to date"}`);
  if (env[URL_VAR] && env[URL_VAR] !== KOKORO_ADDRESS) {
    error(`kokoro: warning: ${URL_VAR}=${env[URL_VAR]} in the environment overrides the secrets file`);
  }
  const envOverridesCtl = Boolean(env[CTL_VAR]) && !ctlEntries(env[CTL_VAR]).includes(ctlPath);
  if (envOverridesCtl) {
    error(`kokoro: warning: ${CTL_VAR}=${env[CTL_VAR]} in the environment overrides the secrets file`);
  }

  // A server already up (likely the panel's) stays up: restarted only onto a new
  // checkout, never stopped. Otherwise start it just for the probe.
  const wasRunning = ctl(ctlPath, "status").status === 0;
  let launched;
  if (wasRunning && checkout.updated) {
    log(`kokoro: restarting the running server on ${KOKORO_FASTAPI_REF}`);
    launched = ctl(ctlPath, "restart");
  } else if (wasRunning) {
    log("kokoro: server already running; checking it answers");
    launched = { status: 0 };
  } else {
    log(`kokoro: starting the server to check it answers (the first start downloads the model; up to ${PROBE_TIMEOUT_MS / 1000} s)`);
    launched = ctl(ctlPath, "start");
  }
  const answered = launched.status === 0 && (await probe({ fetch, now, sleep }));
  if (!wasRunning) ctl(ctlPath, "stop");
  if (!answered) {
    error(`kokoro: the server did not answer at ${KOKORO_ADDRESS}; see ${logPath}`);
    return 1;
  }
  log(`kokoro: installed; ${KOKORO_ADDRESS} answered${wasRunning ? "" : ", server stopped"}`);
  // The panel caches secrets at boot, so it only sees the new lines after a restart.
  log(
    envOverridesCtl
      ? `kokoro: restart the panel to use it: \`pnpm stop && pnpm start\` (${CTL_VAR} in the environment must list ${ctlPath} too, or the panel will not start and stop Kokoro)`
      : "kokoro: restart the panel to use it: `pnpm stop && pnpm start` (it then starts and stops Kokoro itself)",
  );
  return 0;
}

// Run only when executed directly, never on import.
if (process.argv[1] && realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url))) {
  process.exit(await main(process.argv.slice(2)));
}
