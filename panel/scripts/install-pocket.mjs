#!/usr/bin/env node
/*
 * Installer for the local Pocket TTS servers (kyutai pocket-tts).
 *
 * Installs `pocket-tts==POCKET_TTS_VERSION` into a uv venv (Python 3.12) under
 * `PAVILIO_POCKET_DIR ?? ~/.local/share/pavilio/pocket-tts`, writes `pocketctl`
 * (start|stop|restart|status|log) and `pocket.conf` (the selected servers and the
 * workspace voices dir) beside it, and points the panel secrets file at them:
 * POCKET_TTS_BASE_URL (English, :8895), POCKET_PL_TTS_BASE_URL (Polish, :8896),
 * POCKET_VOICE_FILES_URL (a read-only file server for <workspace>/.pavilio/voices, :8897),
 * POCKET_TTS_CLONING (1 when a Hugging Face token file exists) and pocketctl in the
 * `:`-separated PANEL_TTS_SERVER_CTL list. It then starts the servers once, probes
 * `GET /health` on each (and the file server on :8897) and stops them again (servers already
 * running are only probed). A port that answers while pocketctl is stopped belongs to another
 * service: the install stops there. `pocketctl status` exits 0 (all up), 3 (none) or 4 (some).
 *
 * Re-running the same selection changes nothing. Uninstalling one server drops its address
 * and its conf entry; the last one takes the venv, pocketctl and the shared lines too.
 *
 * The secrets editing and the ctl handling are install-kokoro.mjs's. Every side effect
 * (uv, pocketctl, fetch, clock) is injected into `main`, so tests need no network.
 *
 * Driven by `pnpm install:speech`, which passes the selected servers and the workspace root.
 */
import { spawnSync } from "node:child_process";
import { chmodSync, existsSync, mkdirSync, readFileSync, rmdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join, resolve } from "node:path";
import {
  CTL_VAR,
  LINE,
  PROBE_INTERVAL_MS,
  PROBE_REQUEST_MS,
  PROBE_TIMEOUT_MS,
  ctlEntries,
  defaultCtl,
  defaultWhich,
  fileValue,
  installHint,
  readSecretLines,
  unquote,
  withValues,
  writeSecretLines,
} from "./install-kokoro.mjs";

export const POCKET_TTS_VERSION = "4.0.1";
export const POCKET_PORTS = { pocket: 8895, "pocket-pl": 8896, voiceFiles: 8897 };
export const POCKET_PL_REVISION = "a8630f2a39055d3e5a91acb7922e31bd0c506cfe";
const POCKET_PL_REPO = "hf://shefowl/pocket-tts-polish-6l";
export const POCKET_PL_CONFIG = `${POCKET_PL_REPO}/config.yaml@${POCKET_PL_REVISION}`;
export const POCKET_PL_DEFAULT_VOICE = `${POCKET_PL_REPO}/reference.wav@${POCKET_PL_REVISION}`;

const HOST = "127.0.0.1";
const SERVER_IDS = ["pocket", "pocket-pl"];
const URL_VARS = { pocket: "POCKET_TTS_BASE_URL", "pocket-pl": "POCKET_PL_TTS_BASE_URL" };
const FILES_VAR = "POCKET_VOICE_FILES_URL";
const CLONING_VAR = "POCKET_TTS_CLONING";
const FILES_URL = `http://${HOST}:${POCKET_PORTS.voiceFiles}`;
const address = (id) => `http://${HOST}:${POCKET_PORTS[id]}`;
// Everything the installer or pocketctl puts in the install dir; uninstall removes only these.
const OWN_ENTRIES = ["venv", "pocketctl", "pocket.conf", "pocket.pid", "pocket-pl.pid", "voices.pid", "pocket.log"];

/** Shell single-quoting, so a path with spaces survives `. pocket.conf`. */
function shq(value) {
  return `'${String(value).replace(/'/g, `'\\''`)}'`;
}

export function pocketctlScript() {
  return `#!/bin/bash
# Generated by panel/scripts/install-pocket.mjs; re-run \`pnpm install:speech\` instead of editing.
# Usage: pocketctl start|stop|restart|status|log
set -u

DIR="$(cd "$(dirname "\${BASH_SOURCE[0]}")" && pwd)"
LOG="$DIR/pocket.log"
POCKET_SERVERS=""
POCKET_VOICES_DIR=""
# shellcheck disable=SC1091
[ -f "$DIR/pocket.conf" ] && . "$DIR/pocket.conf"
export PATH="$PATH:$HOME/.local/bin:$HOME/.cargo/bin:/opt/homebrew/bin:/usr/local/bin"

has_server() { [[ " $POCKET_SERVERS " == *" $1 "* ]]; }

started_at() {
  ps -o lstart= -p "$1" 2>/dev/null | tr -s ' ' | sed 's/^ //; s/ $//'
}

# The pidfile holds the pid and its start time; a pid alone could have been reused.
running() {
  local file="$DIR/$1.pid" pid recorded
  [ -f "$file" ] || return 1
  { read -r pid; read -r recorded; } <"$file"
  if [[ "$pid" =~ ^[0-9]+$ ]] && [ -n "$recorded" ] && kill -0 "$pid" 2>/dev/null \\
    && [ "$(ps -o pgid= -p "$pid" 2>/dev/null | tr -d ' ')" = "$pid" ] \\
    && [ "$(started_at "$pid")" = "$recorded" ]; then
    PID="$pid"
    return 0
  fi
  unlink "$file" 2>/dev/null
  return 1
}

launch() {
  local name="$1"
  shift
  if running "$name"; then
    echo "pocket: $name already running (pid $PID)"
    return 0
  fi
  set -m
  nohup "$@" >>"$LOG" 2>&1 </dev/null &
  local pid=$!
  set +m
  printf '%s\\n%s\\n' "$pid" "$(started_at "$pid")" >"$DIR/$name.pid"
  # A server that cannot bind its port (or crashes at once) exits right away: do not report it started.
  sleep 0.5
  if ! kill -0 "$pid" 2>/dev/null; then
    unlink "$DIR/$name.pid" 2>/dev/null
    echo "pocket: $name exited at once (port in use?); see $LOG" >&2
    FAILED=1
    return 1
  fi
  echo "pocket: $name started (pid $pid, log $LOG)"
}

halt() {
  local name="$1"
  running "$name" || return 0
  local pid="$PID" i=0
  # POCKETCTL_KILL and POCKETCTL_TERM_STEPS are test seams (a no-op killer simulates a survivor).
  local killer="\${POCKETCTL_KILL:-kill}" steps="\${POCKETCTL_TERM_STEPS:-40}"
  "$killer" -TERM -- "-$pid" 2>/dev/null || "$killer" -TERM "$pid" 2>/dev/null
  while kill -0 "$pid" 2>/dev/null && [ "$i" -lt "$steps" ]; do
    sleep 0.25
    i=$((i + 1))
  done
  "$killer" -KILL -- "-$pid" 2>/dev/null || "$killer" -KILL "$pid" 2>/dev/null
  i=0
  while kill -0 "$pid" 2>/dev/null && [ "$i" -lt 8 ]; do
    sleep 0.25
    i=$((i + 1))
  done
  # A survivor keeps its pidfile, so the next stop (or status) still finds it.
  if kill -0 "$pid" 2>/dev/null; then
    echo "pocket: $name (pid $pid) did not exit" >&2
    return 1
  fi
  unlink "$DIR/$name.pid" 2>/dev/null
  echo "pocket: $name stopped"
}

FAILED=0

start() {
  FAILED=0
  if has_server pocket; then
    # English cloning needs the gated weights, which need the Hugging Face login.
    if [ -s "$HOME/.cache/huggingface/token" ]; then
      HF_TOKEN="$(cat "$HOME/.cache/huggingface/token")"
      export HF_TOKEN
    fi
    launch pocket "$DIR/venv/bin/pocket-tts" serve --host ${HOST} --port ${POCKET_PORTS.pocket}
    unset HF_TOKEN
  fi
  if has_server pocket-pl; then
    launch pocket-pl "$DIR/venv/bin/pocket-tts" serve --host ${HOST} --port ${POCKET_PORTS["pocket-pl"]} \\
      --config ${POCKET_PL_CONFIG} \\
      --default-voice ${POCKET_PL_DEFAULT_VOICE}
  fi
  mkdir -p "$POCKET_VOICES_DIR"
  launch voices "$DIR/venv/bin/python" -m http.server ${POCKET_PORTS.voiceFiles} --bind ${HOST} -d "$POCKET_VOICES_DIR"
  return "$FAILED"
}

stop() {
  local rc=0
  halt voices || rc=1
  halt pocket-pl || rc=1
  halt pocket || rc=1
  return "$rc"
}

case "\${1:-}" in
  start) start ;;
  stop) stop ;;
  restart) stop && start ;;
  status)
    # 0 = every configured server runs, 3 = none does, 4 = only some (a start completes the rest).
    up=0
    want=1
    running voices && { echo "pocket: voices running (pid $PID)"; up=$((up + 1)); }
    for name in pocket pocket-pl; do
      has_server "$name" || continue
      want=$((want + 1))
      running "$name" && { echo "pocket: $name running (pid $PID)"; up=$((up + 1)); }
    done
    if [ "$up" -eq "$want" ]; then exit 0; fi
    if [ "$up" -eq 0 ]; then echo "pocket: stopped"; exit 3; fi
    echo "pocket: partly running"
    exit 4
    ;;
  log)
    echo "$LOG"
    [ -f "$LOG" ] && tail -n "\${2:-100}" "$LOG"
    ;;
  *)
    echo "usage: $0 start|stop|restart|status|log" >&2
    exit 2
    ;;
esac
`;
}

function confText(servers, voicesDir) {
  return `POCKET_SERVERS=${shq(servers.join(" "))}\nPOCKET_VOICES_DIR=${shq(voicesDir)}\n`;
}

/** The servers named in an existing pocket.conf, in canonical order. */
function readConfServers(confPath) {
  if (!existsSync(confPath)) return [];
  const match = /^POCKET_SERVERS='([^']*)'/m.exec(readFileSync(confPath, "utf8"));
  const named = match ? match[1].split(" ") : [];
  return SERVER_IDS.filter((id) => named.includes(id));
}

function writeIfChanged(path, text, mode) {
  if (!existsSync(path) || readFileSync(path, "utf8") !== text) writeFileSync(path, text, { mode });
  chmodSync(path, mode);
}

function defaultRun(cmd, args) {
  const res = spawnSync(cmd, args, { stdio: ["ignore", "inherit", "inherit"] });
  return { status: res.status ?? 1 };
}

/** One quick GET: does anything answer there at all? */
async function answers(url, { fetch }) {
  try {
    return (await fetch(url, { signal: AbortSignal.timeout(PROBE_REQUEST_MS) })).ok === true;
  } catch {
    return false;
  }
}

async function probe(url, { fetch, now, sleep }) {
  const deadline = now() + PROBE_TIMEOUT_MS;
  for (;;) {
    try {
      const res = await fetch(url, { signal: AbortSignal.timeout(PROBE_REQUEST_MS) });
      if (res.ok) return true;
    } catch {
      // Not up yet: the first start downloads the weights.
    }
    if (now() >= deadline) return false;
    await sleep(PROBE_INTERVAL_MS);
  }
}

/**
 * `servers`: the Pocket servers to install (or, with `uninstall`, to remove).
 * Resolves `{ ok }` instead of exiting, so a test can drive it with fakes.
 */
export async function main(
  { servers, uninstall = false, workspaceRoot },
  {
    env = process.env,
    platform = process.platform,
    which = defaultWhich,
    run = defaultRun,
    ctl = defaultCtl,
    fetch = globalThis.fetch,
    now = Date.now,
    sleep = (ms) => new Promise((r) => setTimeout(r, ms)),
    log = console.log,
    error = console.error,
    panelDir = resolve(import.meta.dirname, ".."),
  } = {},
) {
  const home = env.HOME || homedir();
  const installDir = resolve(env.PAVILIO_POCKET_DIR || join(home, ".local", "share", "pavilio", "pocket-tts"));
  const venvDir = join(installDir, "venv");
  const ctlPath = join(installDir, "pocketctl");
  const confPath = join(installDir, "pocket.conf");
  const logPath = join(installDir, "pocket.log");
  const versionMarker = join(venvDir, ".pocket-tts-version");
  const tokenFile = join(home, ".cache", "huggingface", "token");
  const secretsFile = join(resolve(panelDir, env.PANEL_AUTH_STATE_DIR || join(home, ".panel")), "secrets.env");
  const selected = SERVER_IDS.filter((id) => servers.includes(id));
  const voicesDir = join(workspaceRoot, ".pavilio", "voices");

  if (uninstall) {
    const remaining = readConfServers(confPath).filter((id) => !selected.includes(id));
    const last = remaining.length === 0;
    if (existsSync(ctlPath)) {
      if (last) {
        // Removing the pid files and the script of a server that is still up would leave it unmanaged.
        if (ctl(ctlPath, "stop").status !== 0) {
          error(`pocket: could not stop the servers with ${ctlPath}; nothing was removed. Stop them, then re-run`);
          return { ok: false };
        }
      } else if ([0, 4].includes(ctl(ctlPath, "status").status)) {
        writeIfChanged(confPath, confText(remaining, voicesDir), 0o644);
        ctl(ctlPath, "restart");
      }
    }
    if (last) {
      for (const name of OWN_ENTRIES) rmSync(join(installDir, name), { recursive: true, force: true });
      try {
        rmdirSync(installDir);
      } catch (e) {
        if (e.code === "ENOTEMPTY" || e.code === "EEXIST") log(`pocket: kept ${installDir}; it holds files this installer did not create`);
        else if (e.code !== "ENOENT") throw e;
      }
    } else if (existsSync(confPath)) {
      writeIfChanged(confPath, confText(remaining, voicesDir), 0o644);
    }
    // A server's address goes only while it still names this install.
    const ownValues = new Map(selected.map((id) => [URL_VARS[id], address(id)]));
    if (last) {
      ownValues.set(FILES_VAR, FILES_URL);
      ownValues.set(CLONING_VAR, undefined);
    }
    const kept = readSecretLines(secretsFile).flatMap((line) => {
      const match = LINE.exec(line);
      if (!match) return [line];
      const value = unquote(match[2]);
      if (ownValues.has(match[1])) {
        const own = ownValues.get(match[1]);
        return own === undefined || value === own ? [] : [line];
      }
      if (last && match[1] === CTL_VAR) {
        const entries = ctlEntries(value);
        if (!entries.includes(ctlPath)) return [line];
        const rest = entries.filter((entry) => entry !== ctlPath);
        return rest.length ? [`${CTL_VAR}=${rest.join(":")}`] : [];
      }
      return [line];
    });
    if (existsSync(secretsFile)) writeSecretLines(secretsFile, kept, now);
    log(last ? `pocket: removed ${installDir}` : `pocket: removed ${selected.join(", ")}; ${remaining.join(", ")} stays`);
    if (last && ctlEntries(env[CTL_VAR]).includes(ctlPath)) {
      error(`pocket: warning: ${CTL_VAR} in the environment still lists ${ctlPath}; update it separately`);
    }
    return { ok: true };
  }

  if (!selected.length) {
    error("pocket: no server selected");
    return { ok: false };
  }
  if (!which("uv")) {
    error("pocket: missing uv; install with:");
    for (const hint of installHint(platform, ["uv"])) error(`  ${hint}`);
    return { ok: false };
  }
  if (ctlPath.includes(":")) {
    error(`pocket: ${ctlPath} contains ':'; ${CTL_VAR} cannot hold a path with ':' — set PAVILIO_POCKET_DIR to a path without one`);
    return { ok: false };
  }

  mkdirSync(installDir, { recursive: true });
  // Selecting one server never drops the other that is already installed.
  const installed = readConfServers(confPath);
  const all = SERVER_IDS.filter((id) => selected.includes(id) || installed.includes(id));

  const venvReady = existsSync(versionMarker) && readFileSync(versionMarker, "utf8").trim() === POCKET_TTS_VERSION;
  if (!venvReady) {
    log(`pocket: creating the venv and installing pocket-tts==${POCKET_TTS_VERSION} (a few minutes)`);
    const venv = run("uv", ["venv", "--python", "3.12", venvDir]);
    const cpuFlags =
      platform === "linux"
        ? ["--extra-index-url", "https://download.pytorch.org/whl/cpu", "--index-strategy", "unsafe-best-match"]
        : [];
    const install =
      venv.status === 0
        ? run("uv", ["pip", "install", "--python", join(venvDir, "bin", "python"), `pocket-tts==${POCKET_TTS_VERSION}`, ...cpuFlags])
        : venv;
    if (install.status !== 0) {
      error(`pocket: installing pocket-tts failed (exit ${install.status})`);
      return { ok: false };
    }
    writeFileSync(versionMarker, `${POCKET_TTS_VERSION}\n`);
  }
  mkdirSync(voicesDir, { recursive: true });
  writeIfChanged(ctlPath, pocketctlScript(), 0o755);
  writeIfChanged(confPath, confText(all, voicesDir), 0o644);

  // Same test as pocketctl's `[ -s token ]`: an empty token file is no login.
  const hasToken = existsSync(tokenFile) && statSync(tokenFile).size > 0;
  const lines = readSecretLines(secretsFile);
  const fileCtls = ctlEntries(fileValue(lines, CTL_VAR));
  const entries = {
    ...Object.fromEntries(all.map((id) => [URL_VARS[id], address(id)])),
    [FILES_VAR]: FILES_URL,
    [CLONING_VAR]: hasToken ? "1" : "0",
    ...(fileCtls.includes(ctlPath) ? {} : { [CTL_VAR]: [...fileCtls, ctlPath].join(":") }),
  };
  const changed = writeSecretLines(secretsFile, withValues(lines, entries), now);
  log(`pocket: ${secretsFile} ${changed ? "updated" : "already up to date"}`);
  // scripts/panel prefers a non-empty environment value over the secrets file; that one is the user's to edit.
  const envOverridesCtl = Boolean(env[CTL_VAR]) && !ctlEntries(env[CTL_VAR]).includes(ctlPath);
  if (envOverridesCtl) {
    error(`pocket: warning: ${CTL_VAR}=${env[CTL_VAR]} in the environment overrides the secrets file`);
  }
  if (all.includes("pocket") && !hasToken) {
    log("pocket: English voice cloning is off (no Hugging Face login). To turn it on:");
    log("  1. accept the terms at https://huggingface.co/kyutai/pocket-tts");
    log("  2. run `uvx hf auth login`");
    log("  3. re-run this installer");
  }

  // 0: all up; 4: only some (the missing ones are started, the others left alone); else none.
  const before = ctl(ctlPath, "status").status;
  const wasRunning = before === 0;
  const stopAfter = before !== 0 && before !== 4;
  let launched = { status: 0 };
  if (stopAfter) {
    // Nothing of ours runs, so anything answering on these ports is another service.
    for (const url of [...all.map((id) => `${address(id)}/health`), `${FILES_URL}/`]) {
      if (await answers(url, { fetch })) {
        error(`pocket: ${url} already answers but pocketctl is not running: another service holds that port; free it and re-run`);
        return { ok: false };
      }
    }
  }
  if (wasRunning) {
    log("pocket: servers already running; checking they answer");
  } else if (before === 4) {
    log("pocket: some servers are already running; starting the rest and checking they answer");
    launched = ctl(ctlPath, "start");
  } else {
    log(`pocket: starting the servers to check they answer (the first start downloads the weights; up to ${PROBE_TIMEOUT_MS / 1000} s each)`);
    launched = ctl(ctlPath, "start");
  }
  let answered = launched.status === 0;
  if (!answered) error("pocket: a server exited right after it started (port in use?)");
  // The file server serves <workspace>/.pavilio/voices; its directory listing answers 200.
  const targets = [...all.map((id) => [id, `${address(id)}/health`]), ["voices", `${FILES_URL}/`]];
  for (const [id, url] of targets) {
    if (!answered) break;
    answered = await probe(url, { fetch, now, sleep });
    if (!answered) error(`pocket: ${id} did not answer at ${url}`);
  }
  if (stopAfter) ctl(ctlPath, "stop");
  if (!answered) {
    error(`pocket: the install is kept; see ${logPath}`);
    return { ok: false };
  }
  log(`pocket: installed ${all.join(", ")}${stopAfter ? "; servers stopped" : ""}`);
  log(
    envOverridesCtl
      ? `pocket: restart the panel to use it: \`pnpm stop && pnpm start\` (${CTL_VAR} in the environment must list ${ctlPath} too, or the panel will not start and stop Pocket)`
      : "pocket: restart the panel to use it: `pnpm stop && pnpm start` (it then starts and stops Pocket itself)",
  );
  return { ok: true };
}
