import { existsSync, unlinkSync, writeFileSync } from "fs";
import { join } from "path";

import { ENTITY_KINDS, walkWikiPages, type WikiPage } from "./pages";

/**
 * Deterministic generator for `wiki/index.md` and every section index.
 *
 * - Sections are the top-level dirs of the wiki (`raw/` is never walked). The root index lists
 *   one line per section and nothing else; root-level pages (`overview.md`, `open-questions.md`)
 *   are reached by their fixed names, so they are type-checked but never listed. `log.md` is
 *   outside the page walk altogether.
 * - `<section>/index.md` lists `title — description` per page. Entities are grouped by `kind`;
 *   other sections group nested pages under their first sub-dir (`sources/notes/…` → `## notes`).
 * - `repos/` is two-level: `repos/index.md` lists one line per repo, and each
 *   `repos/<repo>/index.md` lists that repo's pages. A repo line borrows the description of its
 *   `ARCHITECTURE.md`.
 * - Every `index.md` is output, never input: excluded from listings and the type check. A
 *   generated one (`type: index`) whose section or repo has no pages left is removed; a
 *   hand-written `index.md` (any other type, or none) is never touched.
 * - Links are D14 wikilinks (`[[wiki/concepts/x|Title]]`): the same form every other wiki page
 *   uses, rendered by the panel and resolved by `links.ts`, so an agent follows them like any
 *   other link. Consumers of the backlink map (lint orphans) must therefore ignore index pages as
 *   link sources.
 * - No timestamps and code-unit ordering everywhere, so an unchanged wiki rebuilds byte-identical.
 */

export type IndexResult =
  | { ok: true; written: string[]; removed: string[] } // wiki-relative paths, sorted
  | { ok: false; error: string; page?: string }; // `page` is wiki-relative

/** Fixed order and one-line blurbs of the known sections; unknown sections follow, sorted. */
const KNOWN_SECTIONS: Record<string, string> = {
  sources: "One source page per record",
  entities: "People, repositories, services and organizations",
  concepts: "Domain knowledge",
  repos: "Code-level notes per repository",
  questions: "Answered questions worth keeping",
  notes: "Free-form notes",
};
const SECTION_ORDER = Object.keys(KNOWN_SECTIONS);

const GENERATED = "<!-- Generated by `scripts/wiki index` — edits here are overwritten. -->";

const byString = (a: string, b: string) => (a < b ? -1 : a > b ? 1 : 0);
const isIndexFile = (path: string) => path === "index.md" || path.endsWith("/index.md");
const capitalize = (s: string) => s.charAt(0).toUpperCase() + s.slice(1);
const pageCount = (n: number) => `${n} ${n === 1 ? "page" : "pages"}`;

/** `[`, `]`, `|` and line breaks would end a wikilink early. */
const linkLabel = (s: string) => s.replace(/[[\]|]/g, "").replace(/\s+/g, " ").trim();
const oneLine = (s: string) => s.replace(/\s+/g, " ").trim();

function firstHeading(body: string): string | undefined {
  let fence: string | null = null;
  for (const line of body.split("\n")) {
    const open = /^ {0,3}(`{3,}|~{3,})/.exec(line);
    if (open) {
      if (fence === null) fence = open[1][0];
      else if (open[1][0] === fence) fence = null;
      continue;
    }
    if (fence !== null) continue;
    const heading = /^# +(.+?)\s*#*\s*$/.exec(line);
    if (heading) return heading[1];
  }
  return undefined;
}

/** Frontmatter `title`, else the first `# ` heading, else the filename stem. */
export function pageTitle(page: WikiPage): string {
  const stem = page.path.slice(page.path.lastIndexOf("/") + 1).replace(/\.md$/, "");
  return linkLabel(page.frontmatter.title ?? firstHeading(page.body) ?? "") || stem;
}

const link = (target: string, label: string) => `[[wiki/${target}|${label}]]`;

function pageLine(page: WikiPage): string {
  const target = page.path.replace(/\.md$/, "");
  const description = oneLine(page.frontmatter.description ?? "");
  return `- ${link(target, pageTitle(page))}${description ? ` — ${description}` : ""}`;
}

type Group = { heading?: string; lines: string[] };

function renderIndex(title: string, description: string, groups: Group[]): string {
  const out = ["---", "type: index", `description: ${JSON.stringify(description)}`, "---", GENERATED, "", `# ${title}`, ""];
  for (const group of groups) {
    if (group.lines.length === 0) continue;
    if (group.heading) out.push(`## ${group.heading}`, "");
    out.push(...group.lines, "");
  }
  return out.join("\n");
}

/** Pages directly under `prefix` first, then one group per first sub-dir. */
function groupByDir(pages: WikiPage[], prefix: string): Group[] {
  const top: string[] = [];
  const nested = new Map<string, string[]>();
  for (const page of pages) {
    const rest = page.path.slice(prefix.length);
    const slash = rest.indexOf("/");
    if (slash === -1) top.push(pageLine(page));
    else {
      const dir = rest.slice(0, slash);
      if (!nested.has(dir)) nested.set(dir, []);
      nested.get(dir)!.push(pageLine(page));
    }
  }
  return [{ lines: top }, ...[...nested.keys()].sort(byString).map((dir) => ({ heading: dir, lines: nested.get(dir)! }))];
}

function groupByKind(pages: WikiPage[]): Group[] {
  const kinds: (string | undefined)[] = [...ENTITY_KINDS, undefined];
  return kinds.map((kind) => ({
    heading: capitalize(kind ?? "other"),
    lines: pages.filter((p) => p.frontmatter.kind === kind).map(pageLine),
  }));
}

/**
 * Render every index file from an already-walked page list, without touching disk.
 * Returns wiki-relative path → content, or the first untyped page in path order.
 */
export function renderIndexes(pages: WikiPage[]): { ok: true; files: Map<string, string> } | { ok: false; error: string; page: string } {
  const content = pages.filter((p) => !isIndexFile(p.path));
  const untyped = content.find((p) => !p.frontmatter.type?.trim());
  if (untyped) return { ok: false, error: "page has no type", page: untyped.path };

  const bySection = new Map<string, WikiPage[]>();
  for (const page of content) {
    const slash = page.path.indexOf("/");
    if (slash === -1) continue; // root-level page: never listed
    const section = page.path.slice(0, slash);
    if (!bySection.has(section)) bySection.set(section, []);
    bySection.get(section)!.push(page);
  }
  const sections = [
    ...SECTION_ORDER.filter((s) => bySection.has(s)),
    ...[...bySection.keys()].filter((s) => !(s in KNOWN_SECTIONS)).sort(byString),
  ];

  const files = new Map<string, string>();
  const rootLines: string[] = [];
  for (const section of sections) {
    const sectionPages = bySection.get(section)!;
    const label = capitalize(section);
    const blurb = KNOWN_SECTIONS[section];
    const count = pageCount(sectionPages.length);
    rootLines.push(`- ${link(`${section}/index`, label)} — ${blurb ? `${blurb} (${count})` : count}`);

    const prefix = `${section}/`;
    let groups: Group[];
    if (section === "entities") groups = groupByKind(sectionPages);
    else if (section === "repos") groups = renderRepos(sectionPages, files);
    else groups = groupByDir(sectionPages, prefix);
    files.set(`${section}/index.md`, renderIndex(label, `${label} section index`, groups));
  }
  files.set("index.md", renderIndex("Wiki", "Sections of this wiki, one line each", [{ lines: rootLines }]));
  return { ok: true, files };
}

/** Write each `repos/<repo>/index.md` into `files`; return the groups of `repos/index.md`. */
function renderRepos(pages: WikiPage[], files: Map<string, string>): Group[] {
  const loose: string[] = [];
  const repos = new Map<string, WikiPage[]>();
  for (const page of pages) {
    const rest = page.path.slice("repos/".length);
    const slash = rest.indexOf("/");
    if (slash === -1) loose.push(pageLine(page));
    else {
      const repo = rest.slice(0, slash);
      if (!repos.has(repo)) repos.set(repo, []);
      repos.get(repo)!.push(page);
    }
  }
  const repoLines: string[] = [];
  for (const repo of [...repos.keys()].sort(byString)) {
    const repoPages = repos.get(repo)!;
    const prefix = `repos/${repo}/`;
    const architecture = repoPages.find((p) => p.path === `${prefix}ARCHITECTURE.md`);
    const description = oneLine(architecture?.frontmatter.description ?? "");
    const count = pageCount(repoPages.length);
    repoLines.push(`- ${link(`${prefix}index`, linkLabel(repo))} — ${description ? `${description} (${count})` : count}`);
    files.set(`${prefix}index.md`, renderIndex(repo, `Code-level notes for ${repo}`, groupByDir(repoPages, prefix)));
  }
  return [{ lines: loose }, { lines: repoLines }];
}

/**
 * Regenerate every index under `wikiDir`. All-or-nothing: on an untyped page nothing is written.
 * Generated indexes left without pages are removed.
 * Maps onto the CLI contract `scripts/wiki index <p>` → `{written, removed}` | exit 1 `{error, page}`.
 */
export function buildIndex(wikiDir: string): IndexResult {
  if (!existsSync(wikiDir)) return { ok: false, error: "wiki dir not found" };
  const pages = walkWikiPages(wikiDir);
  const rendered = renderIndexes(pages);
  if (!rendered.ok) return rendered;
  const written = [...rendered.files.keys()].sort(byString);
  const removed = pages
    .filter((p) => isIndexFile(p.path) && p.frontmatter.type === "index" && !rendered.files.has(p.path))
    .map((p) => p.path);
  for (const path of written) writeFileSync(join(wikiDir, ...path.split("/")), rendered.files.get(path)!);
  for (const path of removed) unlinkSync(join(wikiDir, ...path.split("/")));
  return { ok: true, written, removed };
}
