import { describe, expect, it } from "vitest";
import {
  SEC_MS_GEC_VERSION,
  createSecMsGecGenerator,
  generateSecMsGecV2,
  secMsGecTicks,
} from "../secMsGec";
import golden from "./fixtures/secMsGec.vectors.json";

// Golden vectors come from rany2/edge-tts 7.3.1 (the reference that Microsoft
// accepts) via `fixtures/gen_sec_ms_gec_vectors.py`. Byte-for-byte equality is
// the whole contract: one wrong bit and the endpoint answers 403.
describe("Sec-MS-GEC v2 token", () => {
  it("was generated by an edge-tts release that speaks v2", () => {
    expect(golden.source).toMatch(/^edge-tts 7\.3\./);
    expect(golden.vectors.length).toBeGreaterThanOrEqual(5);
  });

  it("pairs with the same Sec-MS-GEC-Version as the reference", () => {
    expect(SEC_MS_GEC_VERSION).toBe(golden.secMsGecVersion);
  });

  it.each(golden.vectors)("matches the reference at t=$unixSeconds", ({ unixSeconds, token }) => {
    expect(generateSecMsGecV2(unixSeconds)).toBe(token);
  });

  it("has the <16 hex>-<64 hex> shape", () => {
    expect(generateSecMsGecV2(1_791_590_400)).toMatch(/^[0-9A-F]{16}-[0-9A-F]{64}$/);
  });

  it("is stable within a 5-minute window and changes across it", () => {
    expect(secMsGecTicks(1_791_590_400)).toBe(secMsGecTicks(1_791_590_699.9));
    expect(generateSecMsGecV2(1_791_590_400)).toBe(generateSecMsGecV2(1_791_590_699.9));
    expect(generateSecMsGecV2(1_791_590_700)).not.toBe(generateSecMsGecV2(1_791_590_699.9));
  });

  it("takes its clock by injection", () => {
    const [first] = golden.vectors;
    expect(createSecMsGecGenerator(() => first.unixSeconds)()).toBe(first.token);
  });
});
